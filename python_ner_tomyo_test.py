def normal(text: str) -> str:
    """Том/жижиг үсэг, цэг тэмдгийн ялгааг шалгалтад тооцохгүй."""
    return re.sub(r"\s+", " ", re.sub(r"[^\wөүӨҮ]+", " ", text.lower())).strip()


def keyword_found(keyword: str, reply: str) -> bool:
    """Нэг түлхүүр үг эсвэл түүнтэй ойролцоо нэршил хариултад бий эсэх."""
    choices = (keyword, *EQUIVALENTS.get(keyword, ()))
    return any(normal(choice) in reply for choice in choices)


def is_correct(reply: str, keywords: tuple[str, ...]) -> bool:
    """Яг ижил бичвэр биш, гол санаа нь тохирсон эсэхийг шалгана.

    Бүх түлхүүр санаа байвал шууд зөв. Урт, утгатай хариултад гол санааны
    тал нь байвал бас зөв гэж авна — аман хариулт жишээ өгүүлбэрээс өөрөөр
    хэлэгддэг учраас.
    """
    reply = normal(reply)
    if not reply:
        return False

    found = sum(keyword_found(word, reply) for word in keywords)
    if found == len(keywords):
        return True

    word_count = len(reply.split())
    return word_count >= 3 and found >= (len(keywords) + 1) // 2


def hint(answer: str, keywords: tuple[str, ...]) -> str:
    """Бүтэн хариултаас илүү богино дохио."""
    return "Түлхүүр санаа: " + ", ".join(keywords) + "."


def self_check() -> bool:
    while True:
        choice = input("Өөрийн үнэлгээ — зөв байсан уу? (t/y эсвэл үгүй/n): ").strip().lower()
        if choice in {"t", "y", "тийм", "yes"}:
            return True
        if choice in {"үгүй", "ugui", "n", "no"}:
            return False
        print("t (тийм) эсвэл n (үгүй) гэж оруулна уу.")


def ask_question(question: tuple[int, str, str, tuple[str, ...]]) -> bool:
    number, text, answer, keywords = question
    print(f"\n{number}. {text}")
    print("Хариултаа бич. [h=дохио, a=хариулт, s=алгасах, q=гарах]")

    while True:
        reply = input("> ").strip()
        command = reply.lower()

        if command == "h":
            print(hint(answer, keywords))
        elif command == "a":
            print(f"Зөв хариулт: {answer}")
            # Дохио/хариулт харсны дараа ч дахин хэлж, зөв гэж авах боломжтой.
        elif command == "s":
            print(f"Алгаслаа. Зөв хариулт: {answer}")
            return False
        elif command == "q":
            raise KeyboardInterrupt
        elif is_correct(reply, keywords):
            print("Зөв! ✅")
            return True
        else:
            print("Автоматаар баталгаажсангүй.")
            print(f"Зөв хариулт: {answer}")
            return self_check()


def choose_count() -> int:
    while True:
        raw = input(f"Хэдэн асуултаар шалгуулах вэ? (1–{len(QUESTIONS)}, Enter=10): ").strip()
        if not raw:
            return 10
        if raw.isdigit() and 1 <= int(raw) <= len(QUESTIONS):
            return int(raw)
        print("1–50 хооронд тоо оруулна уу.")


def main() -> None:
    print("=" * 48)
    print("       PYTHON АМАН ТЕСТ — санамсаргүй асуулт")
    print("=" * 48)
    count = choose_count()
    chosen = random.sample(QUESTIONS, count)
    correct = 0

    try:
        for index, question in enumerate(chosen, start=1):
            print(f"\n--- Асуулт {index}/{count} ---")
            if ask_question(question):
                correct += 1
    except (KeyboardInterrupt, EOFError):
        print("\nТест дууслаа.")
        return

    percent = correct / count * 100
    print("\n" + "=" * 48)
    print(f"Дүн: {correct}/{count} зөв ({percent:.0f}%)")
    if percent >= 80:
        print("Маш сайн!")
    elif percent >= 50:
        print("Сайн байна. Буруу асуултуудаа дахин давтаарай.")
    else:
        print("Хариултуудаа дахин давтаад дахин оролдоорой.")


